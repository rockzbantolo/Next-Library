using Next.Clients.Core;
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Next.Clients.Backup
{
    internal static class SqlBackup
    {
        public static async Task<bool> DumpAsync(Base db, string filePath)
        {
            Logs.Write(db.Logger, "BACKUP", db.Name, $"Starting full backup → {filePath}");
            Directory.CreateDirectory(Path.GetDirectoryName(filePath)!);

            var tables = await db.QueryAsync<string>(
                "SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_NAME");

            using var writer = new StreamWriter(filePath, false, new UTF8Encoding(false));
            await writer.WriteLineAsync($"-- SQL Server Full Backup: {db.Name} @ {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            await writer.WriteLineAsync("-- Generated by Next.Clients.Database");
            await writer.WriteLineAsync("SET NOCOUNT ON; GO");

            foreach (var table in tables)
            {
                Logs.Write(db.Logger, "BACKUP", db.Name, $"Processing table: {table}");

                await writer.WriteLineAsync($"\n-- =========================================");
                await writer.WriteLineAsync($"-- Table: [{table}]");
                await writer.WriteLineAsync($"-- =========================================");

                var createScript = await GetCreateTableScript(db, table);
                await writer.WriteLineAsync(createScript ?? $"-- CREATE script not available for [{table}]");

                await DumpTableData(db, table, writer);
            }

            Logs.Write(db.Logger, "BACKUP", db.Name, $"Backup completed → {filePath}");
            return true;
        }

        private static async Task<string> GetCreateTableScript(Base db, string table)
        {
            try
            {
                return await db.QueryFirstOrDefaultAsync<string>(
                    "SELECT OBJECT_DEFINITION(OBJECT_ID(@t))", new { t = table });
            }
            catch (Exception ex)
            {
                Logs.Write(db.Logger, "WARN", db.Name, $"CREATE script failed for {table}: {ex.Message}");
                return null;
            }
        }

        private static async Task DumpTableData(Base db, string table, StreamWriter writer)
        {
            try
            {
                var rows = await db.QueryAsync<dynamic>($"SELECT * FROM [{table}]");
                int count = 0;

                foreach (var row in rows)
                {
                    var values = new List<string>();
                    foreach (var prop in row.GetType().GetProperties())
                    {
                        var val = prop.GetValue(row);
                        if (val == null || val is DBNull) values.Add("NULL");
                        else if (val is string || val is DateTime || val is Guid)
                            values.Add($"'{val.ToString()!.Replace("'", "''")}'");
                        else if (val is bool b) values.Add(b ? "1" : "0");
                        else if (val is byte[] bytes)
                            values.Add($"0x{BitConverter.ToString(bytes).Replace("-", "")}");
                        else
                            values.Add(val.ToString()!);
                    }
                    await writer.WriteLineAsync($"INSERT INTO [{table}] VALUES ({string.Join(", ", values)});");
                    count++;
                }

                if (count > 0)
                    Logs.Write(db.Logger, "BACKUP", db.Name, $"Dumped {count} row(s) from [{table}]");
            }
            catch (Exception ex)
            {
                Logs.Write(db.Logger, "ERROR", db.Name, $"Data dump failed for {table}: {ex.Message}");
            }
        }
    }
}
